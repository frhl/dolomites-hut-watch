"""Public STATUS.md: last-run times and OK / FAILING per check. Nothing else.

Built from the private state, but only from fields that do not depend on availability
(run times and consecutive-failure counters), so the file - and the keep-alive commit
that page-watch makes with it - is identical whether huts are full or have beds.
"""

from __future__ import annotations

import datetime as dt

from . import beds, beds_config, nuvolau, pagewatch, pagewatch_config, state

OUT = state.ROOT / "STATUS.md"


def _t(s: str | None) -> str:
    if not s:
        return "never"
    return state.parse(s).astimezone(dt.timezone.utc).strftime("%Y-%m-%d %H:%M")


def _health(rec: dict | None) -> str:
    if not rec:
        return "not checked yet"
    n = rec.get("consecutive_failures", 0)
    return "OK" if n == 0 else f"FAILING ({n} run{'s' if n > 1 else ''} in a row)"


def render(now: dt.datetime | None = None) -> str:
    now = now or state.now()
    pages = state.load(pagewatch.STATE_FILE)
    bst = state.load(beds.STATE_FILE)
    nst = state.load(nuvolau.STATE_FILE)
    rows = []
    for n in beds_config.NIGHTS:
        for bh in n.huts:
            if bh.hut.params.get("blocked_on_ci"):
                rows.append((n.night, bh.hut.name, "Mac (hourly)", "not published"))
            else:
                rows.append((n.night, bh.hut.name, "cancellation-watch",
                             _health(bst.get("entries", {}).get(f"{n.night}/{bh.hut.id}"))))
    for n in nuvolau.NIGHTS:
        rows.append((n.night, nuvolau.HUT.name, "cancellation-watch",
                     _health(nst.get("entries", {}).get(f"{n.night}/{nuvolau.HUT.id}"))))
    rows.append((None, f"{nuvolau.HUT.name} booking form", "cancellation-watch",
                 _health(nst.get("opening"))))
    for url in nuvolau.ANNOUNCE_PAGES:
        rows.append((None, f"{nuvolau.HUT.name} page {url}", "cancellation-watch",
                     _health(nst.get("pages", {}).get(url))))
    for p in pagewatch_config.PAGES:
        h = pagewatch_config.hut(p.hut)
        rows.append((h.night, f"{h.name}: {p.label}", "page-watch", _health(pages.get("pages", {}).get(p.id))))

    lines = [
        "# Status",
        "",
        "Public health summary, regenerated by `page-watch` every 4 hours. Results, availability",
        "and page text are kept in a private repository: this page only says whether each check",
        "ran and whether it worked. How each hut is checked: [CHECKERS.md](CHECKERS.md).",
        "",
        f"Generated: {now.astimezone(dt.timezone.utc):%Y-%m-%d %H:%M} UTC",
        "",
        "| Watch | Last run (UTC) |",
        "|---|---|",
        f"| page-watch (every 4 h) | {_t((pages.get('last_run') or {}).get('at'))} |",
        f"| cancellation-watch (every 15 min) | {_t(bst.get('last_run'))} |",
        f"| Nuvolau watch (every 5-15 min) | {_t(nst.get('last_run'))} |",
        "",
        "| Night | Check | Run by | Status |",
        "|---|---|---|---|",
    ]
    for night, what, by, health in rows:
        lines.append(f"| {night.strftime('%d %b %Y') if night else '-'} | {what} | {by} | {health} |")
    return "\n".join(lines) + "\n"


def write() -> None:
    text = render()
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
